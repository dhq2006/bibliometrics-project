import pandas as pd

# ====================== 1. 自动读取并转换 WoS 文本 ======================
def parse_wos_txt(filepath):
    records = []
    current = {}
    with open(filepath, 'r', encoding='utf-8') as f:
        lines = f.readlines()

    for line in lines:
        line = line.strip()
        if not line:
            continue
        if len(line) >= 3 and line[2] == ' ':
            field = line[:2]
            val = line[3:].strip()
            if field in current:
                current[field] += ' ' + val
            else:
                current[field] = val
            if field == 'UT':
                records.append(current.copy())
                current = {}
    return pd.DataFrame(records)

